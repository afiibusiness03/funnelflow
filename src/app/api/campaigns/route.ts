import { requireAccount } from '@/lib/security/access'
import { apiError, checkOrigin, readJson } from '@/lib/security/http'
import { campaignSchema } from '@/lib/security/schemas'
import { NextResponse } from 'next/server'
import { createClient, createServiceClient } from '@/lib/supabase/server'
import { generateQRSvg } from '@/lib/qr/generate'

export async function GET() {
  let account
  try { account = await requireAccount({ write: false }) } catch (error) { return apiError(error) }
  const { supabase, profile: userData } = account

  const { data, error } = await supabase
    .from('campaigns')
    .select('*, product:products!campaigns_product_id_fkey(*), promotion:promotions(*)')
    .eq('tenant_id', userData.tenant_id)
    .order('created_at', { ascending: false })

  if (error) return NextResponse.json({ error: 'Unable to save this change' }, { status: 500 })
  return NextResponse.json({ data })
}

export async function POST(request: Request) {
  let account
  try { account = await requireAccount({ write: true }); checkOrigin(request) } catch (error) { return apiError(error) }
  const { supabase, profile: userData } = account

  const tenant = (userData.tenant as unknown) as { brand_color: string; max_campaigns: number; plan: string } | null

  // Check campaign limit
  const { count } = await supabase
    .from('campaigns')
    .select('*', { count: 'exact', head: true })
    .eq('tenant_id', userData.tenant_id)

  if ((count ?? 0) >= (tenant?.max_campaigns ?? 1) && (tenant?.max_campaigns ?? 1) !== 999999) {
    return NextResponse.json({ error: 'Campaign limit reached. Please upgrade your plan.' }, { status: 403 })
  }

  let body
  try { body = await readJson(request, campaignSchema) } catch (error) { return apiError(error) }
  const {
    name, product_id, product_ids, promotion_id,
    require_order_verify, smart_routing, smart_routing_threshold,
    language, review_url, custom_thank_you_msg,
    custom_color, custom_logo_url,
  } = body

  const primaryProductId = product_id || (Array.isArray(product_ids) && product_ids.length > 0 ? product_ids[0] : null)

  if (!name || !primaryProductId) {
    return NextResponse.json({ error: 'name and product_id are required' }, { status: 400 })
  }

  // Verify primaryProductId belongs to user's tenant
  const { data: productCheck } = await supabase
    .from('products')
    .select('id')
    .eq('id', primaryProductId)
    .eq('tenant_id', userData.tenant_id)
    .single()

  if (!productCheck) {
    return NextResponse.json({ error: 'Invalid or unauthorized product_id' }, { status: 400 })
  }

  // Verify promotion_id belongs to user's tenant if provided
  if (promotion_id) {
    const { data: promoCheck } = await supabase
      .from('promotions')
      .select('id')
      .eq('id', promotion_id)
      .eq('tenant_id', userData.tenant_id)
      .single()

    if (!promoCheck) {
      return NextResponse.json({ error: 'Invalid or unauthorized promotion_id' }, { status: 400 })
    }
  }

  const requestedProducts = [...new Set(body.product_ids?.length ? body.product_ids : [primaryProductId])]
  const { data: ownedProducts, error: ownershipError } = await supabase.from('products').select('id').eq('tenant_id', userData.tenant_id).in('id', requestedProducts)
  if (ownershipError || ownedProducts?.length !== requestedProducts.length) return NextResponse.json({ error: 'Invalid product selection' }, { status: 400 })

  // 1. Insert campaign (short_code auto-generated by DB trigger)
  const serviceClient = createServiceClient()
  const { data: campaign, error: insertError } = await serviceClient
    .from('campaigns')
    .insert({
      tenant_id: userData.tenant_id,
      name,
      product_id: primaryProductId,
      promotion_id: promotion_id || null,
      status: 'active',
      require_order_verify: require_order_verify ?? true,
      smart_routing: smart_routing ?? true,
      smart_routing_threshold: smart_routing_threshold ?? 4,
      language: language ?? 'en',
      review_url: review_url || null,
      custom_thank_you_msg: custom_thank_you_msg || null,
      custom_color: custom_color || null,
      custom_logo_url: custom_logo_url || null,
    })
    .select()
    .single()

  if (insertError || !campaign) {
    return NextResponse.json({ error: 'Unable to create campaign. Check your plan limit and selection.' }, { status: 500 })
  }

  const { error: linksError } = await serviceClient.rpc('replace_campaign_products', { p_campaign: campaign.id, p_tenant: userData.tenant_id, p_products: requestedProducts })
  if (linksError) {
    await serviceClient.from('campaigns').delete().eq('id', campaign.id).eq('tenant_id', userData.tenant_id)
    return NextResponse.json({ error: 'Unable to save product selection' }, { status: 500 })
  }

  // 2. Generate QR SVG with brand color
  const brandColor = custom_color ?? tenant?.brand_color ?? '#6366f1'
  try {
    const qrSvg = await generateQRSvg({ shortCode: campaign.qr_short_code, color: brandColor })
    // Store QR as data URI on the campaign
    const qrDataUri = `data:image/svg+xml;base64,${Buffer.from(qrSvg).toString('base64')}`
    await serviceClient
      .from('campaigns')
      .update({ qr_code_url: qrDataUri })
      .eq('id', campaign.id)
    campaign.qr_code_url = qrDataUri
  } catch (qrError) {
    console.error('QR generation failed:', qrError)
    // Non-fatal — campaign still created
  }

  return NextResponse.json({ data: campaign }, { status: 201 })
}
